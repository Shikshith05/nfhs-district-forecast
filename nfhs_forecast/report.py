"""Markdown data report (outputs/data_report.md)."""

from __future__ import annotations

from datetime import date

import numpy as np
import pandas as pd


def md_table(df: pd.DataFrame, floatfmt: str = "{:.3g}") -> str:
    """Minimal markdown table (avoids a tabulate dependency)."""
    def fmt(v):
        if isinstance(v, (float, np.floating)):
            return "" if np.isnan(v) else floatfmt.format(v)
        return str(v).replace("|", "\\|")
    cols = [str(c) for c in df.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    lines += ["| " + " | ".join(fmt(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join(lines)


def _pct(x: float) -> str:
    return "n/a" if x is None or (isinstance(x, float) and np.isnan(x)) else f"{100 * x:.1f}%"


def write_data_report(path, *, log45: dict, log6: dict, panel: pd.DataFrame, name_map: pd.DataFrame,
                      codebook: pd.DataFrame, variants: pd.DataFrame, audit_summary: dict,
                      audit_pairs: pd.DataFrame, audit_by_district: pd.DataFrame, cfg: dict) -> None:
    L: list[str] = []
    add = L.append
    add("# Data report")
    add("")
    add(f"Generated by `scripts/run_pipeline.py` on {date.today().isoformat()}. "
        "NFHS-6 values appear here only as descriptive counts and in the audit; they are never "
        "used for training, tuning, feature engineering or model selection.")
    add("")

    # ------------------------------------------------------------------
    add("## 1. Rows, districts and indicators per round")
    add("")
    rows = []
    raw_ind = {4: log45["raw_indicator_texts"], 5: log45["raw_indicator_texts"],
               6: int(variants[variants.source == "nfhs6"].raw_text.nunique())}
    raw_rows = {4: log45["raw_rows"], 5: log45["raw_rows"], 6: log6["raw_rows"]}
    raw_d = {4: log45["raw_districts"], 5: log45["raw_districts"], 6: log6["raw_districts"]}
    for rnd in (4, 5, 6):
        p = panel[panel["round"] == rnd]
        rows.append({
            "round": f"NFHS-{rnd}", "raw rows (file)": raw_rows[rnd], "raw districts": raw_d[rnd],
            "raw indicator texts": raw_ind[rnd], "clean rows": len(p),
            "districts": p.district_uid.nunique(), "canonical indicators": p.indicator_id.nunique(),
            "non-missing values": int(p.value.notna().sum()), "missing": _pct(p.value.isna().mean()),
        })
    add(md_table(pd.DataFrame(rows)))
    add("")
    add("NFHS-4 and NFHS-5 come from the same file (India.csv: the NFHS-5 district fact sheets with "
        "their NFHS-4 comparison column), so their raw row counts are the same file.")
    add("")

    # ------------------------------------------------------------------
    add("## 2. Missingness and suppression")
    add("")
    z = log45["zero_rules"]
    add("**India.csv (NFHS-4/5)** has no empty cells: the parser wrote `na` and suppressed `*` cells "
        "as `0`. Zeros were reclassified as follows (DECISIONS D08):")
    add("")
    add(f"- whole district-round not available (>= {cfg['cleaning']['district_zero_share_missing']:.0%} zeros): "
        f"{z['district_rounds_not_available']} district-rounds, {z['district_round_not_available_rows']:,} values")
    add(f"- indicator not measured in that round (>= {cfg['cleaning']['indicator_zero_share_missing']:.0%} zeros): "
        f"{z['indicator_not_in_round_rows']:,} values")
    add(f"- isolated zero treated as suppressed (indicator has no plausible near-zero values): "
        f"{z['zero_treated_as_suppressed_rows']:,} values")
    add(f"- zeros kept as true zeros: {z['zeros_kept_as_true_zero']:,} values")
    add("")
    add(f"**NFHS-6:** `*` (suppressed, < 25 unweighted cases) in the NFHS-6 column: "
        f"{log6['suppressed_nfhs6']:,} cells; in the file's own NFHS-5 column: "
        f"{log6['suppressed_nfhs5_in_file']:,}. Rows with `small_sample_flag == True`: "
        f"{log6['small_sample_rows']:,} (the flag is per row and does not say which round's value is "
        "small-sample; every `*` row is flagged). No bracketed values remain in the file "
        "(the cleaner strips them anyway).")
    add("")
    mr = (panel.assign(missing_reason=panel.missing_reason.fillna("(present)"))
          .groupby(["round", "missing_reason"]).size().unstack("round").fillna(0).astype(int))
    mr.columns = [f"NFHS-{c}" for c in mr.columns]
    add(md_table(mr.reset_index().rename(columns={"missing_reason": "value status"})))
    add("")

    # ------------------------------------------------------------------
    add("## 3. Excluded and corrected data")
    add("")
    for st, n in log6["excluded_states"].items():
        add(f"- NFHS-6 `{st}`: {n} rows excluded (several districts merged under one name; DECISIONS D05).")
    for st, di in log45["excluded_districts"]:
        add(f"- India.csv `{st} | {di}`: placeholder district, {log45['excluded_rows']} rows excluded.")
    for fx in log45["renamed_blocks"]:
        add(f"- India.csv `{fx['state']} | {fx['district_in_source']}` held a second block of "
            f"{fx['rows']} rows keyed `{fx['district_key']}`; renamed to `{fx['renamed_to']}` (source parse error).")
    for c in log45["conflicting_duplicates"]:
        add(f"- India.csv duplicate with conflicting values set to missing: `{c['State']} | {c['District']} | "
            f"{c['Indicator']} | NFHS-{c['round']}`.")
    for k, n in log6["state_sheet_districts"].items():
        add(f"- NFHS-6 `{k}` has {n} rows taken from the STATE fact sheet (different indicator numbering); "
            "kept and matched by text only.")
    add("")

    # ------------------------------------------------------------------
    add("## 4. District matching (no boundary harmonisation)")
    add("")
    mc = name_map.method.value_counts().rename_axis("method").reset_index(name="districts")
    add(md_table(mc))
    add("")
    core = name_map[name_map.core]
    add(f"**Core districts** (matched unambiguously in all three rounds, no NFHS-6 boundary change, "
        f"NFHS-4 and NFHS-5 values present, NFHS-5 audit agreement >= "
        f"{cfg['matching']['audit_min_district_agreement']:.0%}): **{len(core)}** in "
        f"{core.state_key.nunique()} states/UTs.")
    add("")
    ex = name_map[~name_map.core].exclusion_reason.value_counts().rename_axis("exclusion reason")
    add(md_table(ex.reset_index(name="districts")))
    add("")
    add("Full decisions with scores: `data/processed/district_name_map.csv`; lists: "
        "`data/processed/matched_districts.csv`, `data/processed/unmatched_districts.csv`.")
    add("")

    # ------------------------------------------------------------------
    add("## 5. Indicator matching")
    add("")
    m = codebook.match_method.value_counts().rename_axis("cross-round match").reset_index(name="indicators")
    add(md_table(m))
    add("")
    add(f"- comparable in all three rounds (high/medium-confidence text match, no definition flag, "
        f"percentage, NFHS-4/5 coverage >= {cfg['indicators']['min_coverage_rounds_4_5']:.0%}): "
        f"**{int(codebook.comparable_all_rounds.sum())}**")
    add(f"- included (comparable AND in the core set): **{int(codebook.include.sum())}**")
    add("")
    inc = codebook[codebook.include][["indicator_id", "domain", "se_group", "match_method", "text_nfhs6"]]
    add(md_table(inc))
    add("")
    add("Variant-level review file: `data/processed/indicator_variants.csv`; codebook: "
        "`data/processed/indicator_codebook.csv`.")
    add("")

    # ------------------------------------------------------------------
    add("## 6. Audit: NFHS-6 file's NFHS-5 column vs India.csv NFHS-5")
    add("")
    s = audit_summary
    add(f"Matched district x indicator pairs compared: {s['pairs_compared']:,} "
        f"({s['pairs_both_numeric']:,} with a number in both sources).")
    add("")
    add(f"- **exact agreement** (|diff| < 0.05): **{_pct(s['exact_agreement_rate'])}**")
    add(f"- **within 0.5 points**: **{_pct(s['within_0_5_agreement_rate'])}**")
    add(f"- `*` in the NFHS-6 file: {s['nfhs6file_star_pairs']:,} pairs, of which "
        f"{s['nfhs6file_star_and_india_zero']:,} are `0` in India.csv (confirms India.csv zeros encode "
        f"suppression) and {s['nfhs6file_star_and_india_nonzero']:,} are non-zero.")
    add(f"- `0` in India.csv: {s['india_zero_pairs']:,} pairs; the NFHS-6 file has `*` for "
        f"{s['india_zero_and_nfhs6file_star']:,}, `0` for {s['india_zero_and_nfhs6file_zero']:,} "
        f"and a positive number for {s['india_zero_and_nfhs6file_positive']:,}.")
    add("")
    low = audit_by_district[audit_by_district.audit_within_0_5 < 0.8].merge(
        name_map[["district_uid", "district", "state", "exclusion_reason"]], on="district_uid", how="left")
    if len(low):
        add("Districts whose NFHS-5 values agree poorly (< 80% within 0.5):")
        add("")
        low = low.sort_values("audit_within_0_5")
        add(md_table(low[["state", "district", "audit_pairs", "audit_within_0_5", "exclusion_reason"]]
                     .assign(audit_within_0_5=lambda d: d.audit_within_0_5.map(_pct))))
        add("")
    both = audit_pairs.dropna(subset=["india_clean", "value5_file"]).copy()
    both["abs_diff"] = both["diff"].abs()
    worst = both.sort_values("abs_diff", ascending=False).head(25)
    worst = worst.merge(name_map[["district_uid", "state", "district"]], on="district_uid", how="left")
    add("Worst 25 mismatches:")
    add("")
    add(md_table(worst[["state", "district", "indicator_id", "india_clean", "value5_file", "diff"]]
                 .rename(columns={"india_clean": "India.csv NFHS-5", "value5_file": "NFHS-6 file NFHS-5"}),
                 floatfmt="{:.1f}"))
    add("")
    by_ind = both.assign(within=both.abs_diff <= 0.5).groupby("indicator_id").within.mean().sort_values()
    add("Indicators with the lowest agreement (share within 0.5): " +
        ", ".join(f"`{k}` {_pct(v)}" for k, v in by_ind.head(8).items()) + ".")
    add("")
    add("All pairs: `data/processed/audit_nfhs5_pairs.csv`.")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(L) + "\n")
